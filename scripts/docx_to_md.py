"""Regenerate the Markdown copy of every .docx under docs/sources (audit 2026-10-26b, T3; fix session F7).

Each copy is written next to its .docx as <name>.md, by pandoc (GitHub Markdown), with a first
line naming the source file and its sha256. `tests/test_sources_markdown.py` checks, without
pandoc, that every .docx has a copy whose recorded sha256 matches the .docx as committed, so a
changed .docx with a stale copy fails CI. Never edit the copies by hand; rerun this script.
Requires pandoc. Run from the repository root: python scripts/docx_to_md.py
"""

from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "<!-- generated by scripts/docx_to_md.py from {name}, sha256 {sha}; do not edit by hand -->\n\n"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    for docx in sorted((ROOT / "docs/sources").rglob("*.docx")):
        md = subprocess.run(["pandoc", str(docx), "-t", "gfm", "--wrap=none"],
                            capture_output=True, text=True, check=True).stdout
        out = docx.with_suffix(".md")
        out.write_text(HEADER.format(name=docx.name, sha=sha256(docx)) + md, encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
