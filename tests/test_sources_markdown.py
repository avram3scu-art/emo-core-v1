"""Every .docx under docs/sources has a Markdown copy made by scripts/docx_to_md.py from the same bytes."""

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_every_docx_has_a_current_markdown_copy():
    docx_files = sorted((ROOT / "docs/sources").rglob("*.docx"))
    assert docx_files
    for docx in docx_files:
        md = docx.with_suffix(".md")
        assert md.exists(), f"no copy for {docx.name}: run scripts/docx_to_md.py"
        m = re.match(r"<!-- generated by scripts/docx_to_md.py from (.+), sha256 ([0-9a-f]{64});", md.read_text(encoding="utf-8"))
        assert m, f"{md.name} was not made by scripts/docx_to_md.py"
        assert m.group(1) == docx.name
        assert m.group(2) == hashlib.sha256(docx.read_bytes()).hexdigest(), f"{md.name} is stale: rerun scripts/docx_to_md.py"
